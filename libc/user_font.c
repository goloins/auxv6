static struct user_glyph montecarlo_glyphs[MONTECARLO_GLYPHS];
static struct user_font montecarlo_font;
static int montecarlo_ready;

static void
user_font_init_montecarlo(void)
{
  int i;

  if(montecarlo_ready)
    return;

  memset(&montecarlo_font, 0, sizeof(montecarlo_font));
  strncpy(montecarlo_font.name, "Montecarlo", sizeof(montecarlo_font.name) - 1);
  montecarlo_font.size = MONTECARLO_HEIGHT;
  montecarlo_font.ascent = 12;
  montecarlo_font.descent = 4;
  montecarlo_font.linegap = 0;
  montecarlo_font.is_monospace = 1;
  montecarlo_font.num_glyphs = MONTECARLO_GLYPHS;
  montecarlo_font.glyphs = montecarlo_glyphs;

  for(i = 0; i < MONTECARLO_GLYPHS; i++) {
    struct user_glyph *g;
    g = &montecarlo_glyphs[i];
    g->codepoint = (uint)i;
    g->width = MONTECARLO_WIDTH;
    g->height = MONTECARLO_HEIGHT;
    g->advance_x = MONTECARLO_WIDTH;
    g->advance_y = 0;
    g->bearing_x = 0;
    g->bearing_y = montecarlo_font.ascent;
    g->bitmap = &builtin_font_8x16[i * MONTECARLO_HEIGHT];
    g->bitmap_size = MONTECARLO_HEIGHT;
  }

  montecarlo_ready = 1;
}

const struct user_font *
user_font_builtin_montecarlo(void)
{
  user_font_init_montecarlo();
  return &montecarlo_font;
}

const struct user_glyph *
user_font_get_glyph(const struct user_font *font, uint codepoint)
{
  if(!font || !font->glyphs || font->num_glyphs == 0)
    return 0;
  if(codepoint >= font->num_glyphs)
    codepoint = '?';
  return &font->glyphs[codepoint];
}

int
user_font_char_width(const struct user_font *font, uint codepoint)
{
  const struct user_glyph *g;
  g = user_font_get_glyph(font, codepoint);
  return g ? g->advance_x : MONTECARLO_WIDTH;
}

int
user_font_text_width(const struct user_font *font, const char *text, int len)
{
  int i;
  int w;

  if(!font || !text || len <= 0)
    return 0;

  w = 0;
  for(i = 0; i < len; i++) {
    uchar ch;
    ch = (uchar)text[i];
    w += user_font_char_width(font, (uint)ch);
  }
  return w;
}
