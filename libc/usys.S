#include "syscall.h"
#include "traps.h"

#define SYSCALL(name) \
  .globl name; \
  name: \
    movl $SYS_ ## name, %eax; \
    int $T_SYSCALL; \
    ret

#define SYSCALL_NUM(name, num) \
  .globl name; \
  name: \
    movl $num, %eax; \
    int $T_SYSCALL; \
    ret

