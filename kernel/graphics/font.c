/*
 * Render 8-bit font glyph to pixels
 */
void
font_render_glyph_8bpp(struct font *font, const struct glyph *glyph,
                       uchar *pixels, int pitch,
                       uint fg, uint bg)
{
    int x, y;
    const uchar *bitmap;

    if(!font || !glyph || !pixels)
        return;

    bitmap = glyph->bitmap;

    for(y = 0; y < glyph->height; y++) {
        uchar row = bitmap[y];
        uchar *row_ptr = pixels;
        for(x = 0; x < glyph->width; x++) {
            if(row & (1 << (7 - x))) {
                row_ptr[x] = (uchar)fg;
            } else {
                row_ptr[x] = (uchar)bg;
            }
        }
        pixels += pitch;
    }
}

/*
 * Calculate width of text
 */
int
font_text_width(struct font *font, const uint *codepoints, int count)
{
    int width = 0;
    int i;

    if(!font || !codepoints)
        return 0;

    for(i = 0; i < count; i++) {
        const struct glyph *g = font_get_glyph(font, codepoints[i]);
        if(g)
            width += g->advance_x;
    }

    return width;
}

/*
 * Get text height (line height)
 */
int
font_text_height(struct font *font)
{
    if(!font)
        return 0;

    return font->size;
}

/*
 * Get character width
 */
int
font_char_width(struct font *font, uint codepoint)
{
    const struct glyph *g;

    if(!font)
        return 0;

    g = font_get_glyph(font, codepoint);
    if(!g)
        return font->size; /* Default to monospace */

    return g->advance_x;
}
