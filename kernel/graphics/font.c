/*
 * Get a glyph from a font
 */
const struct glyph *
font_get_glyph(struct font *font, uint codepoint)
{
    static struct glyph glyph_cache;
    int glyph_height;

    if(!font || codepoint >= FONT_CHARS)
        return 0;

    /* Clamp to ASCII for now */
    if(codepoint >= 128)
        codepoint = '?';

    glyph_height = font->size;
    if(glyph_height <= 0 || glyph_height > FONT_HEIGHT)
        glyph_height = FONT_HEIGHT;

    /* Fill in glyph structure */
    memset(&glyph_cache, 0, sizeof(glyph_cache));
    glyph_cache.codepoint = codepoint;
    glyph_cache.width = FONT_WIDTH;
    glyph_cache.height = glyph_height;
    glyph_cache.advance_x = FONT_WIDTH;
    glyph_cache.advance_y = 0;
    glyph_cache.bearing_x = 0;
    glyph_cache.bearing_y = font->ascent;
    glyph_cache.bitmap = builtin_font_bitmap(font, codepoint);
    glyph_cache.bitmap_size = FONT_HEIGHT;

    return &glyph_cache;
}

/*
 * Check if font has a glyph
 */
int
font_has_glyph(struct font *font, uint codepoint)
{
    if(!font)
        return 0;

    /* Builtin fonts have all ASCII */
    if(font_is_builtin(font) && codepoint < 128)
        return 1;

    return 0;
}

